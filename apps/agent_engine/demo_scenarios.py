    """A single QA/demo conversation scenario."""

    id: str
    template_slug: str
    title: str
    customer_message: str
    expected_intent: str
    acceptable_intents: tuple[str, ...] = ()
    expected_signals: tuple[str, ...] = ()
    expect_lead: bool = True
    expect_task: bool = False
    expect_handoff: bool = False
    safety_must_not_contain: tuple[str, ...] = ()
    demo_notes: str = ""
    suggested_channel: str = "web_chat"


