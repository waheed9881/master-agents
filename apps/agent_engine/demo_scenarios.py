def get_scenarios_for_slug(template_slug: str) -> list[DemoScenario]:
    """Return all scenarios for a given agent template slug."""
    return [s for s in SCENARIOS if s.template_slug == template_slug]


def get_scenario_by_id(scenario_id: str) -> DemoScenario | None:
    """Return a single scenario by ID."""
    for scenario in SCENARIOS:
        if scenario.id == scenario_id:
            return scenario
    return None


def scenario_count_by_slug() -> dict[str, int]:
    """Return scenario counts keyed by template slug."""
    counts: dict[str, int] = {}
    for scenario in SCENARIOS:
        counts[scenario.template_slug] = counts.get(scenario.template_slug, 0) + 1
    return counts
